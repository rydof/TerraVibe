#!/usr/bin/env python3
"""Samples named colour ramps from a locally installed Terraria pack into palette_data.py.

Only hex colours are written; no pixels leave the pack. build.py never imports this.
Usage: sample_palette.py --pack assets/terraria-pack/Images --out tools/art/palette_data.py
"""
import argparse
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from png import load_pixels

# Tiles_N.png frames are 16 px with a 2 px gap.
FILL = (18, 18, 16, 16)
TOP = (0, 0, 16, 16)
WHOLE = (0, 0, 288, 270)  # a full sheet, for materials whose fill frame is flat
CAP = (144, 234, 16, 16)  # a frame that is entirely surface growth

# family -> (png, box, n). n colours, dark -> light, named by SUFFIXES.
SOURCES = {
    "DIRT": ("Tiles_0.png", WHOLE, 4),
    "STONE": ("Tiles_1.png", FILL, 4),
    "GRASS": ("Tiles_2.png", CAP, 3),
    "SAND": ("Tiles_53.png", FILL, 3),
    "MUD": ("Tiles_59.png", FILL, 3),
    "JUNGLE": ("Tiles_60.png", CAP, 3),
    "SNOW": ("Tiles_147.png", FILL, 3),
    "ICE": ("Tiles_161.png", FILL, 3),
    "WOOD": ("Tiles_30.png", FILL, 4),
    "BARK": ("Tiles_5.png", FILL, 3),
    "RING": ("Tiles_5.png", TOP, 2),
    "SANDSTONE": ("Tiles_396.png", FILL, 3),
    "HSAND": ("Tiles_397.png", FILL, 3),
    "GLASS": ("Tiles_54.png", WHOLE, 2),
    "COPPER": ("Tiles_7.png", FILL, 3),
    "IRON": ("Tiles_6.png", FILL, 3),
    "SILVER": ("Tiles_9.png", FILL, 3),
    "GOLD": ("Tiles_8.png", FILL, 3),
    "EBONSTONE": ("Tiles_25.png", FILL, 4),
    "CORRUPT": ("Tiles_23.png", CAP, 3),
    "DEMONITE": ("Tiles_22.png", FILL, 3),
}

# n -> constant-name suffixes, dark -> light ("" is the base colour).
SUFFIXES = {2: ["_D", ""], 3: ["_D", "", "_L"], 4: ["_DD", "_D", "", "_L"]}
# Darkest colours to discard first (outlines, rock behind ore): sample n + drop, keep the lightest n.
DROP = {"DIRT": 2, "GLASS": 2, "COPPER": 3, "IRON": 3, "SILVER": 3, "GOLD": 3, "DEMONITE": 3}
OVERRIDES = {
    "DIRT": ["_P", "_D", "", "_L"],
    "RING": ["_D", ""],
    "GLASS": ["_F", "_G"],
    "WOOD": ["_G", "_D", "", "_L"],
    "EBONSTONE": ["_DD", "_D", "", "_L"],
}


def dominant(img, box, n):
    """The n most frequent opaque colours in box (5 bits/channel), sorted dark -> light."""
    x0, y0, w, h = box
    counts = Counter()
    for row in img[y0 : y0 + h]:
        for r, g, b, a in row[x0 : x0 + w]:
            if a >= 128:
                counts[(r >> 3, g >> 3, b >> 3)] += 1
    top = [c for c, _ in counts.most_common(n)]
    top.sort(key=lambda c: (sum(c), c))
    return ["#%02x%02x%02x" % tuple((v << 3) | (v >> 2) for v in c) for c in top]


def sample(pack):
    out = {}
    for family, (png, box, n) in SOURCES.items():
        path = os.path.join(pack, png)
        if not os.path.exists(path):
            raise FileNotFoundError(path)
        drop = DROP.get(family, 0)
        shades = dominant(load_pixels(path), box, n + drop)[drop:]
        if len(shades) < n:
            raise ValueError("%s: only %d distinct colours in %s %s, need %d" % (family, len(shades), png, box, n))
        for suffix, hexv in zip(OVERRIDES.get(family, SUFFIXES[n]), shades):
            out[family + suffix] = hexv
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pack", default="assets/terraria-pack/Images")
    ap.add_argument("--out", default="tools/art/palette_data.py")
    args = ap.parse_args()
    if not os.path.isdir(args.pack):
        print("run tools/install-terraria-assets.sh", file=sys.stderr)
        return 1
    try:
        data = sample(args.pack)
    except FileNotFoundError as e:
        print("missing %s; run tools/install-terraria-assets.sh" % e, file=sys.stderr)
        return 1
    with open(args.out, "w") as f:
        f.write("# Generated by tools/art/sample_palette.py; hex colours only. Do not edit.\n")
        for k, v in data.items():
            f.write('%s = "%s"\n' % (k, v))
    return 0


if __name__ == "__main__":
    sys.exit(main())
